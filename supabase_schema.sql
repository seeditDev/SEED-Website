-- Create the ai_interview_results table
CREATE TABLE IF NOT EXISTS ai_interview_results (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roll_number text,
    name text,
    email text NOT NULL,
    college text,
    year text,
    department text,
    domain text NOT NULL,
    difficulty text NOT NULL,
    company text NOT NULL,
    score_technical numeric DEFAULT 0,
    score_communication numeric DEFAULT 0,
    score_problem_solving numeric DEFAULT 0,
    score_confidence numeric DEFAULT 0,
    score_overall numeric DEFAULT 0,
    feedback jsonb DEFAULT '{}'::jsonb, -- Store strengths, weaknesses, tips, full conversation logs
    duration_seconds integer DEFAULT 0,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Index on email and college for fast queries
CREATE INDEX IF NOT EXISTS idx_ai_interview_results_email ON ai_interview_results(email);
CREATE INDEX IF NOT EXISTS idx_ai_interview_results_college ON ai_interview_results(college);


